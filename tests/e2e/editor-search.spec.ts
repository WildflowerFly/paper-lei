import { expect, test, type Page } from '@playwright/test'

async function enterText(page: Page, text: string) {
  await page.goto('/')
  await page.locator('.cm-content').click()
  await page.keyboard.press('Control+A')
  await page.keyboard.insertText(text)
  await page.keyboard.press('Control+Home')
}

test('finds and highlights matches and reports empty results', async ({ page }) => {
  await enterText(page, '搜索与预览。搜索与替换。')
  await page.keyboard.press('Control+F')
  const keyword = page.getByRole('textbox', { name: '查找关键词' })
  await expect(keyword).toBeFocused()
  await expect(page.getByRole('textbox', { name: '替换为' })).toBeHidden()
  const panel = page.getByRole('region', { name: '当前文档查找' })
  await keyword.fill('搜索')
  await expect(page.locator('.cm-searchMatch')).toHaveCount(2)
  await expect(panel.getByRole('status')).toHaveText('2 个结果')
  await keyword.press('Enter')
  await expect(panel.getByRole('status')).toHaveText('第 1 项，共 2 项')
  await panel.getByRole('button', { name: '下一个' }).click()
  await expect(panel.getByRole('status')).toHaveText('第 2 项，共 2 项')
  await panel.getByRole('button', { name: '上一个' }).click()
  await expect(panel.getByRole('status')).toHaveText('第 1 项，共 2 项')
  await keyword.fill('不存在')
  await expect(panel.getByRole('status')).toHaveText('无匹配结果')
  await expect(panel.getByRole('button', { name: '下一个' })).toBeDisabled()
  await keyword.press('Escape')
  await expect(panel).toHaveCount(0)
  await expect(page.locator('.cm-content')).toBeFocused()
})

test('opens the source from preview and undoes both replacement operations independently', async ({
  page,
}, info) => {
  await enterText(page, 'item item item')
  await page.getByRole('group', { name: '文档布局' }).getByRole('button', { name: '预览' }).click()
  await page.keyboard.press('Control+H')
  const keyword = page.getByRole('textbox', { name: '查找关键词' })
  await expect(keyword).toBeFocused()
  await keyword.fill('item')
  await page.getByRole('textbox', { name: '替换为' }).fill('文档')
  await page.screenshot({ path: info.outputPath('light.png') })
  await page.getByRole('button', { name: '当前主题' }).click()
  await page.getByRole('button', { name: '当前主题' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.screenshot({ path: info.outputPath('dark.png') })
  const editor = page.locator('.cm-content')
  await page.getByRole('button', { name: '替换当前' }).click()
  await expect(editor).toHaveText('文档 item item')
  await page.getByRole('button', { name: '全部替换' }).click()
  await expect(editor).toHaveText('文档 文档 文档')
  await page.getByRole('button', { name: '关闭查找' }).click()
  await editor.press('Control+Z')
  await expect(editor).toHaveText('文档 item item')
  await editor.press('Control+Z')
  await expect(editor).toHaveText('item item item')
})

test('applies menu formatting to the selection and updates the preview', async ({ page }) => {
  await enterText(page, '选中的文字')
  await page.keyboard.press('Control+A')
  await page.getByRole('button', { name: '格式', exact: true }).click()
  await page.getByRole('menuitem', { name: '粗体' }).click()
  const editor = page.locator('.cm-content')
  await expect(editor).toHaveText('**选中的文字**')
  await expect(page.frameLocator('.preview-frame').locator('strong')).toHaveText('选中的文字')
  await editor.press('Control+Z')
  await expect(editor).toHaveText('选中的文字')
})
